import fs from "node:fs";
import path from "node:path";

/**
 * A cookie jar in the Netscape file format curl reads and writes:
 *
 *   # Netscape HTTP Cookie File
 *   .cds.cern.ch	TRUE	/	TRUE	1757900000	techaro.lol-anubis-auth-...	eyJ...
 *
 * Seven tab-separated columns: domain, include-subdomains flag, path, secure flag,
 * expiry (epoch seconds, 0 for a session cookie), name, value. A leading
 * `#HttpOnly_` on the domain marks an HttpOnly cookie. The format is kept so the
 * jars the Python tool left under `~/.cache/bulk/anubis/` keep working.
 *
 * Matching follows the parts of RFC 6265 that matter for these hosts: host
 * equality or suffix match on the domain, path prefix, the secure flag against
 * the scheme, and expiry against the clock.
 */

export interface Cookie {
  domain: string;
  includeSubdomains: boolean;
  path: string;
  secure: boolean;
  /** Epoch seconds, or 0 for a session cookie. */
  expires: number;
  name: string;
  value: string;
  httpOnly: boolean;
}

const HEADER =
  "# Netscape HTTP Cookie File\n# https://curl.se/docs/http-cookies.html\n# This file was generated by bulk. Edit at your own risk.\n\n";

function domainMatches(cookie: Cookie, host: string): boolean {
  const domain = cookie.domain.replace(/^\./, "").toLowerCase();
  const h = host.toLowerCase();
  if (h === domain) return true;
  return cookie.includeSubdomains && h.endsWith(`.${domain}`);
}

function pathMatches(cookie: Cookie, requestPath: string): boolean {
  const cp = cookie.path || "/";
  if (requestPath === cp) return true;
  if (!requestPath.startsWith(cp)) return false;
  return cp.endsWith("/") || requestPath[cp.length] === "/";
}

export class CookieJar {
  private cookies: Cookie[] = [];

  constructor(readonly file?: string) {}

  static load(file: string): CookieJar {
    const jar = new CookieJar(file);
    if (fs.existsSync(file)) jar.parse(fs.readFileSync(file, "utf-8"));
    return jar;
  }

  static fromText(text: string): CookieJar {
    const jar = new CookieJar();
    jar.parse(text);
    return jar;
  }

  parse(text: string): void {
    for (const raw of text.split("\n")) {
      let line = raw.replace(/\r$/, "");
      if (!line.trim()) continue;
      let httpOnly = false;
      if (line.startsWith("#HttpOnly_")) {
        httpOnly = true;
        line = line.slice("#HttpOnly_".length);
      } else if (line.startsWith("#")) continue;
      const parts = line.split("\t");
      if (parts.length < 7) continue;
      const [domain, sub, cpath, secure, expires, name, ...valueParts] = parts;
      this.cookies.push({
        domain,
        includeSubdomains: sub === "TRUE",
        path: cpath || "/",
        secure: secure === "TRUE",
        expires: Number(expires) || 0,
        name,
        value: valueParts.join("\t"),
        httpOnly,
      });
    }
  }

  serialize(): string {
    const lines = this.cookies.map((c) =>
      [
        (c.httpOnly ? "#HttpOnly_" : "") + c.domain,
        c.includeSubdomains ? "TRUE" : "FALSE",
        c.path,
        c.secure ? "TRUE" : "FALSE",
        String(c.expires),
        c.name,
        c.value,
      ].join("\t"),
    );
    return HEADER + lines.join("\n") + (lines.length ? "\n" : "");
  }

  save(): void {
    if (!this.file) throw new Error("This cookie jar has no file");
    fs.mkdirSync(path.dirname(this.file), { recursive: true });
    const tmp = `${this.file}.${process.pid}.tmp`;
    fs.writeFileSync(tmp, this.serialize(), "utf-8");
    fs.renameSync(tmp, this.file);
  }

  all(): readonly Cookie[] {
    return this.cookies;
  }

  find(predicate: (cookie: Cookie) => boolean): Cookie | undefined {
    return this.cookies.find(predicate);
  }

  /** The `Cookie:` header for a request, or undefined when nothing matches. */
  headerFor(url: string, now = Date.now() / 1000): string | undefined {
    const u = new URL(url);
    const pairs = this.cookies
      .filter((c) => (c.expires === 0 || c.expires > now) && domainMatches(c, u.hostname))
      .filter((c) => pathMatches(c, u.pathname || "/"))
      .filter((c) => !c.secure || u.protocol === "https:")
      .map((c) => `${c.name}=${c.value}`);
    return pairs.length ? pairs.join("; ") : undefined;
  }

  /** Records every `Set-Cookie` of a response against the URL that produced it. */
  applySetCookie(url: string, setCookies: readonly string[], now = Date.now() / 1000): void {
    const u = new URL(url);
    for (const header of setCookies) {
      const cookie = parseSetCookie(header, u, now);
      if (!cookie) continue;
      this.cookies = this.cookies.filter(
        (c) => !(c.name === cookie.name && c.domain === cookie.domain && c.path === cookie.path),
      );
      // An expiry in the past is the server deleting the cookie.
      if (cookie.expires !== 0 && cookie.expires <= now) continue;
      this.cookies.push(cookie);
    }
  }
}

function defaultPath(pathname: string): string {
  if (!pathname.startsWith("/")) return "/";
  const idx = pathname.lastIndexOf("/");
  return idx <= 0 ? "/" : pathname.slice(0, idx);
}

/** One `Set-Cookie` header value → a Cookie, or undefined for a malformed one. */
export function parseSetCookie(
  header: string,
  url: URL,
  now = Date.now() / 1000,
): Cookie | undefined {
  const [pair, ...attrs] = header.split(";");
  const eq = pair.indexOf("=");
  if (eq <= 0) return undefined;
  const name = pair.slice(0, eq).trim();
  const value = pair.slice(eq + 1).trim();
  const cookie: Cookie = {
    domain: url.hostname,
    includeSubdomains: false,
    path: defaultPath(url.pathname),
    secure: false,
    expires: 0,
    name,
    value,
    httpOnly: false,
  };
  for (const attr of attrs) {
    const i = attr.indexOf("=");
    const key = (i === -1 ? attr : attr.slice(0, i)).trim().toLowerCase();
    const val = i === -1 ? "" : attr.slice(i + 1).trim();
    switch (key) {
      case "domain": {
        const d = val.replace(/^\./, "").toLowerCase();
        if (d && (url.hostname === d || url.hostname.endsWith(`.${d}`))) {
          cookie.domain = `.${d}`;
          cookie.includeSubdomains = true;
        }
        break;
      }
      case "path":
        if (val.startsWith("/")) cookie.path = val;
        break;
      case "secure":
        cookie.secure = true;
        break;
      case "httponly":
        cookie.httpOnly = true;
        break;
      case "max-age": {
        const n = Number(val);
        if (Number.isFinite(n)) cookie.expires = Math.floor(now + n);
        break;
      }
      case "expires": {
        if (cookie.expires) break; // Max-Age wins
        const t = Date.parse(val);
        if (!Number.isNaN(t)) cookie.expires = Math.floor(t / 1000);
        break;
      }
      default:
        break;
    }
  }
  return cookie;
}
